export const GW = 2048, GH = 1024;
const X = (lon) => ((lon + 180) / 360) * GW, Y = (lat) => ((90 - lat) / 180) * GH;

function layer(draw, blur = 0) {
  const c = document.createElement('canvas'); c.width = GW; c.height = GH;
  const x = c.getContext('2d');
  x.fillStyle = '#000'; x.fillRect(0, 0, GW, GH);
  if (blur) x.filter = `blur(${blur}px)`;
  draw(x);
  x.filter = 'none';
  return c;
}
const poly = (x, pts, col) => {
  x.fillStyle = col;
  for (const off of [-GW, 0, GW]) {
    x.beginPath(); pts.forEach(([lo, la], i) => (i ? x.lineTo(X(lo) + off, Y(la)) : x.moveTo(X(lo) + off, Y(la)))); x.closePath(); x.fill();
  }
};
const blob = (x, [lon, lat, rx, ry, k]) => {
  for (const off of [-GW, 0, GW]) {
    const cx = X(lon) + off, cy = Y(lat), sx = rx * GW / 360, sy = ry * GH / 180;
    if (cx + sx < 0 || cx - sx > GW) continue;
    x.save(); x.translate(cx, cy); x.scale(sx, sy);
    const g = x.createRadialGradient(0, 0, 0, 0, 0, 1);
    g.addColorStop(0, `rgba(255,255,255,${k})`); g.addColorStop(0.5, `rgba(255,255,255,${k * 0.82})`); g.addColorStop(1, 'rgba(255,255,255,0)');
    x.fillStyle = g; x.beginPath(); x.arc(0, 0, 1, 0, 6.2832); x.fill(); x.restore();
  }
};
const landShape = (x) => {
  for (const p of LAND) poly(x, p, '#fff');
  x.fillStyle = '#fff'; x.beginPath(); x.moveTo(-10, GH + 10);
  for (let lon = -186; lon <= 186; lon += 3) x.lineTo(X(lon), Y(-70.5 - 3.2 * Math.sin(lon * 0.0698) - 2.2 * Math.cos(lon * 0.0349 + 1) - 1.3 * Math.sin(lon * 0.1745 + 2)));
  x.lineTo(GW + 10, GH + 10); x.closePath(); x.fill();
  for (const p of WATER) poly(x, p, '#000');
};
/** 3 枚の白黒の下絵を R・G・B に詰めた 1 枚のテクスチャにする */
function pack(r, g, b) {
  const t = canvasTex(GW, GH, (ctx) => {
    ctx.fillStyle = '#000'; ctx.fillRect(0, 0, GW, GH);
    const tmp = document.createElement('canvas'); tmp.width = GW; tmp.height = GH;
    const tc = tmp.getContext('2d');
    for (const [src, col] of [[r, '#f00'], [g, '#0f0'], [b, '#00f']]) {
      if (!src) continue;
      tc.globalCompositeOperation = 'source-over'; tc.drawImage(src, 0, 0);
      tc.globalCompositeOperation = 'multiply'; tc.fillStyle = col; tc.fillRect(0, 0, GW, GH);
      ctx.globalCompositeOperation = 'lighter'; ctx.drawImage(tmp, 0, 0);
    }
    ctx.globalCompositeOperation = 'source-over';
  }, { srgb: false });
  t.wrapS = THREE.RepeatWrapping; t.generateMipmaps = false; t.minFilter = THREE.LinearFilter; t.magFilter = THREE.LinearFilter; t.needsUpdate = true;
  return t;
}

/** 焼き込みに使う下絵。geo1 = 陸（細・太ぼかし）と氷床、geo2 = 砂漠・森・山、geo3 = 人の多い所 */
export function drawGeo() {
  const landSharp = layer(landShape, 2.2);
  const landWide = layer(landShape, 15);
  const ice = layer((x) => { x.globalCompositeOperation = 'lighter'; ICE.forEach((b) => blob(x, b)); x.fillStyle = '#fff'; x.fillRect(0, Y(-60), GW, GH); }, 5);
  const desert = layer((x) => { x.globalCompositeOperation = 'lighter'; DESERT.forEach((b) => blob(x, b)); }, 7);
  const forest = layer((x) => { x.globalCompositeOperation = 'lighter'; FOREST.forEach((b) => blob(x, b)); }, 12);
  const ranges = layer((x) => {
    x.lineCap = 'round'; x.lineJoin = 'round';
    for (const r of RANGES) for (const off of [-GW, 0, GW]) {
      x.strokeStyle = `rgba(255,255,255,${r.k})`; x.lineWidth = r.w * GW / 360;
      x.beginPath(); r.p.forEach(([lo, la], i) => (i ? x.lineTo(X(lo) + off, Y(la)) : x.moveTo(X(lo) + off, Y(la)))); x.stroke();
    }
  }, 4);
  const people = layer((x) => { x.globalCompositeOperation = 'lighter'; PEOPLE.forEach((b) => blob(x, b)); }, 2);
  return { geo1: pack(landSharp, landWide, ice), geo2: pack(desert, forest, ranges), geo3: pack(people, null, null) };
}
