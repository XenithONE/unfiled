const cache = new Map();
function glyph(ch) {
  let g = cache.get(ch);
  if (g) return g;
  const src = G[ch] || G[ch.toUpperCase()] || G['?'];
  const rows = src.split('|');
  let minC = 5, maxC = -1;
  const cells = [];
  for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (rows[r][c] === '#') { cells.push([c, r]); if (c < minC) minC = c; if (c > maxC) maxC = c; }
  if (maxC < 0) { minC = 0; maxC = 2; }
  g = { cells, minC, w: maxC - minC + 1 };
  cache.set(ch, g);
  return g;
}

/** 文字列の幅（px）。mono=true で等幅 */
export function pixWidth(str, s, { mono = false, gap = 1 } = {}) {
  let w = 0;
  for (const ch of str) w += (mono ? 5 : glyph(ch).w) * s + gap * s;
  return Math.max(0, w - gap * s);
}

/** ドット文字を描く。y は上端。 */
export function pixText(ctx, str, x, y, s, color = '#fff', opt = {}) {
  const { align = 'left', mono = false, gap = 1, shadow = null, outline = null, count = Infinity } = opt;
  const total = pixWidth(str, s, { mono, gap });
  let x0 = Math.round(align === 'center' ? x - total / 2 : align === 'right' ? x - total : x);
  const y0 = Math.round(y);
  const draw = (dx, dy, col) => {
    ctx.fillStyle = col;
    let cx = x0 + dx, n = 0;
    for (const ch of str) {
      if (n++ >= count) break;
      const g = glyph(ch);
      const off = mono ? 0 : g.minC;
      for (const [c, r] of g.cells) ctx.fillRect(cx + (c - off) * s, y0 + dy + r * s, s, s);
      cx += (mono ? 5 : g.w) * s + gap * s;
    }
  };
  if (outline) {
    const o = outline.size || s;
    for (const [dx, dy] of [[-o, 0], [o, 0], [0, -o], [0, o], [-o, -o], [o, -o], [-o, o], [o, o]]) draw(dx, dy, outline.color || '#000');
  }
  if (shadow) draw(shadow.dx ?? s, shadow.dy ?? s, shadow.color || 'rgba(0,0,0,0.6)');
  draw(0, 0, color);
  return total;
}
